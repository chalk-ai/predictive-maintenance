"""Train the failure-risk and remaining-useful-life models on a simulated training fleet.

The training fleet comes from the same generator as the demo fleet but with different seeds, so the
demo pumps are never seen in training. Features come from fusion_reference.py, which mirrors the
Chalk feature definitions. The fitted coefficients are written to pumps/model_weights.py, where
pumps/features.py turns them into native Chalk expressions.

    ./train_model.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from sklearn.linear_model import LinearRegression, LogisticRegression
from sklearn.metrics import roc_auc_score

from fusion_reference import MODEL_INPUTS, fused_features
from pumps.sensors import HOURS, random_fleet

HERE = Path(__file__).resolve().parent
HORIZON_H = 12.0
RUL_CAP_H = 72.0


def dataset(seed: int, n: int) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    xs, ys, ruls, degr = [], [], [], []
    ticks_h = np.arange(6.5, HOURS + 0.01, 0.5)
    for spec in random_fleet(n, seed):
        f = fused_features(spec, (ticks_h * 3600).astype(np.int64))
        x = np.stack([f[k] for k in MODEL_INPUTS], axis=1)
        if spec.failure_h is None or spec.fault_onset_h is None:
            alive = np.ones_like(ticks_h, dtype=bool)
            rul = np.full_like(ticks_h, RUL_CAP_H)
            degrading = np.zeros_like(ticks_h, dtype=bool)
        else:
            alive = ticks_h < spec.failure_h
            rul = np.clip(spec.failure_h - ticks_h, 0, RUL_CAP_H)
            degrading = ticks_h > spec.fault_onset_h
        y = (rul <= HORIZON_H) & alive & (spec.failure_h is not None)
        keep = alive & np.all(np.isfinite(x), axis=1)
        xs.append(x[keep])
        ys.append(y[keep])
        ruls.append(rul[keep])
        degr.append(degrading[keep])
    return (
        np.concatenate(xs),
        np.concatenate(ys),
        np.concatenate(ruls),
        np.concatenate(degr),
    )


def main() -> None:
    x, y, rul, degrading = dataset(seed=7, n=160)
    xv, yv, _, _ = dataset(seed=8, n=60)
    mu, sd = x.mean(axis=0), x.std(axis=0)
    clf = LogisticRegression(C=0.05, max_iter=1000).fit((x - mu) / sd, y)
    auc = roc_auc_score(yv, clf.predict_proba((xv - mu) / sd)[:, 1])
    # Remaining useful life is only estimable once a fault is developing; the page shows it only
    # when the risk model says one is.
    reg = LinearRegression().fit(((x - mu) / sd)[degrading], rul[degrading])
    print(f"train rows={len(y)} positives={int(y.sum())} holdout AUC={auc:.3f}")
    # Fold the standardization into the coefficients so the Chalk expression uses raw features.
    w = clf.coef_[0] / sd
    b = float(clf.intercept_[0] - (clf.coef_[0] * mu / sd).sum())
    rw = reg.coef_ / sd
    rb = float(reg.intercept_ - (reg.coef_ * mu / sd).sum())
    lines = [
        '"""Generated by train_model.py. Do not edit by hand."""',
        "",
        f"MODEL_INPUTS = {MODEL_INPUTS!r}",
        f"RISK_HORIZON_H = {HORIZON_H}",
        f"RUL_CAP_H = {RUL_CAP_H}",
        f"HOLDOUT_AUC = {auc:.4f}",
        f"RISK_INTERCEPT = {b!r}",
        f"RISK_WEIGHTS = {[float(v) for v in w]!r}",
        f"RUL_INTERCEPT = {rb!r}",
        f"RUL_WEIGHTS = {[float(v) for v in rw]!r}",
        "",
    ]
    (HERE / "pumps" / "model_weights.py").write_text("\n".join(lines))
    print(
        "risk weights",
        dict(zip(MODEL_INPUTS, np.round(w, 3))),
        "intercept",
        round(b, 3),
    )


if __name__ == "__main__":
    main()
